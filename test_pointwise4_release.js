'use strict';
const fs=require('fs'),assert=require('node:assert/strict');
const G=require('./esp32s3_codegen.js');
const p=process.argv[2]?JSON.parse(fs.readFileSync(process.argv[2],'utf8')):require('./model_zoo_examples.js').getProject('squeezenet_int8_project');
const out=G.generate(p), ini=out.files['platformio.ini'];
assert.equal(out.summary.operators,43);
assert.equal((ini.match(/\[env:/g)||[]).length,1);
assert.match(ini,/-D NOODLE_INT8_POINTWISE_PIXELS=4/);
const cpp=out.files['lib/Noodle/src/noodle_int8_layers.cpp'];
assert.match(cpp,/NOODLE_INT8_POINTWISE_PIXELS/);
assert.equal(cpp,fs.readFileSync('lib/Noodle/src/noodle_int8_layers.cpp','utf8'));
assert(!Object.hasOwn(out.files,'lib/Noodle/src/noodle_i8_nhwc.cpp'));
assert.equal(out.files['model/params.bin'].length,1278904);
console.log('PASS: production-only CHW Pointwise4, 43 ops, model image');
