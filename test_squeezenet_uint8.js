/** Regression: Qualcomm SqueezeNet-1.1 W8A8 import + ESP32-S3 fixed-image export. */
'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const T = require('./tflite_import.js');
const S = require('./studio.js');
const C = require('./firmware_codegen.js');
const path = process.argv[2] || 'squeezenet1_1.tflite';
if (!fs.existsSync(path)) {
  console.error('Usage: node test_squeezenet_uint8.js /path/to/squeezenet1_1.tflite');
  process.exit(2);
}
const bytes = fs.readFileSync(path);
const model = T.inspectTFLite(bytes);
assert.equal(model.schema_version, 3);
assert.equal(model.operators.length, 43);
assert.equal(model.operators.filter(o => o.op === 'CONV_2D').length, 26);
assert.equal(model.operators.filter(o => o.op === 'CONCATENATION').length, 8);
assert.equal(model.operators.filter(o => o.op === 'QUANTIZE').length, 2);
assert.deepEqual(model.inputs.map(i => model.tensors[i].dtype), ['UINT8']);
assert.deepEqual(model.outputs.map(i => model.tensors[i].dtype), ['UINT8']);
const hash = crypto.createHash('sha256').update(bytes).digest('hex');
const project = S.fromTFLiteModel(model, 'squeezenet1_1.tflite', bytes, hash);
assert.equal(project.target, 'esp32s3');
assert.equal(project.layers.length, 43);
assert.equal(project.layers.filter(l => l.kind === 'CONCATENATION').length, 8);
assert.equal(project.layers.filter(l => l.kind === 'QUANTIZE' && l.params === '-').length, 2);
assert.notEqual(project.settings?.apply_pingpong_sequential, true);
assert(project.source.model_base64.length > bytes.length);
assert.deepEqual(Buffer.from(T.base64Decode(project.source.model_base64)), bytes);
assert.deepEqual(S.normalizeProject(JSON.parse(JSON.stringify(project))), project);
const result = S.validate(project);
assert.deepEqual(result.errors, [], result.errors.join('\n'));
assert.equal(result.steps.length, 43);
assert(result.warnings.some(w => w.includes('UINT8')));
assert(result.warnings.some(w => w.includes('ESP32-S3')));
assert(!result.warnings.some(w => w.includes('opquantize1:')));
assert.throws(() => C.generate(project), /Uno|not implemented|unsupported/i);
console.log('PASS: 43 operators, 26 Conv2D, 8 Concat, 2 Quantize, 0 graph validation errors');
const S3 = require('./esp32s3_codegen.js');
const exported = S3.generate(project);
assert.equal(exported.summary.operators,43);
assert.equal(exported.summary.activationBytes,4975136);
assert(exported.summary.xipBytes>1200000&&exported.summary.xipBytes<1400000);
assert.equal(exported.files['model/params.bin'].length,exported.summary.xipBytes);
assert.match(exported.files['src/main.cpp'],/noodle_i8_graph_execute/);
assert.match(exported.files['platformio.ini'],/16MB/);
assert.match(exported.files['platformio.ini'],/pio_flash_model.py/);
assert.match(exported.files['platformio.ini'],/ARDUINO_USB_CDC_ON_BOOT=1/);
assert.match(exported.files['pio_flash_model.py'],/FLASH_EXTRA_IMAGES/);
assert.match(exported.files['src/main.cpp'],/RDYIMG/);
assert.match(exported.files['src/main.cpp'],/IMG/);
assert.doesNotMatch(exported.files['src/main.cpp'],/fixedImage/);
const spec=JSON.parse(exported.files['test/input_spec.json']);
assert.deepEqual(spec.shape,[1,224,224,3]);
assert.equal(spec.bytes,150528);
assert.equal(spec.chunk_bytes,32);
assert.match(exported.files['test/send_tensor.py'],/--image/);
assert.throws(()=>S3.generate({...project,settings:{apply_pingpong_sequential:true}}),/Disable sequential ping-pong/);
const invalid=JSON.parse(JSON.stringify(project));invalid.storage[0].backend='SRAM';
assert.throws(()=>S3.generate(invalid),/PSRAM/);
console.log('UINT8 tensor metadata preserved, JSON roundtrip lossless, ping-pong off, 43 op ESP32-S3 firmware generated.');
console.log('Warnings:', result.warnings);
