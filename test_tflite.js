'use strict';
const assert=require('node:assert/strict');const fs=require('node:fs');const crypto=require('node:crypto');
const T=require('./tflite_import.js'),S=require('./studio.js');
const path=process.argv[2]||'fcn_mnist16_int8.tflite';
const bytes=fs.readFileSync(path);
const model=T.inspectTFLite(bytes);
assert.equal(model.schema_version,3);
assert.equal(model.operators.length,3);
assert.deepEqual(model.operators.map(x=>x.op),['FULLY_CONNECTED','FULLY_CONNECTED','SOFTMAX']);
assert.deepEqual(model.operators[0].inputs,[0,4,3]);
assert.equal(model.operators[0].config.activation,'RELU');
assert.equal(model.tensors[4].parameter_bytes,16384);
assert.equal(model.tensors[3].parameter_bytes,256);
assert.equal(model.tensors[2].parameter_bytes,640);
assert.equal(model.tensors[1].parameter_bytes,40);
assert.equal(model.tensors[4].quantization.scales.length,64);
assert.equal(model.tensors[2].quantization.scales.length,10);
assert.equal(model.tensors[0].quantization.zero_points[0],-128);
assert.equal(model.tensors[5].dtype,'INT8');
const hash=crypto.createHash('sha256').update(bytes).digest('hex');
assert.equal(hash,'3ad48db87134830b4d3bb1f023c389adbe7ae3bd6fbd5d2fbbcc9d4baa9e4cba');
const p=S.fromTFLiteModel(model,'fcn_mnist16_int8.tflite',bytes,hash);
assert.equal(p.target,'uno');assert.equal(p.layers.length,3);
assert.deepEqual(p.layers.map(x=>x.kind),['FCN','FCN','Softmax']);
assert.equal(p.layers[0].params,'PROGMEM');
assert.equal(p.layers[0].op_options.activation,'RELU');
assert.equal(p.layers[0].parameter_tensors.length,2);
assert.equal(p.storage.length,4);
assert.equal(p.source.model_size_bytes,bytes.length);
assert.deepEqual(Buffer.from(T.base64Decode(p.source.model_base64)),bytes);
const check=S.validate(p);assert.deepEqual(check.errors,[],check.errors.join('; '));
assert.deepEqual(check.warnings,[],check.warnings.join('; '));
assert.equal(check.steps.length,3);
const roundtrip=S.normalizeProject(JSON.parse(JSON.stringify(p)));
assert.deepEqual(roundtrip,p);
assert.equal(roundtrip.source.model_base64,p.source.model_base64);
assert.equal(T.inspectTFLite(T.base64Decode(roundtrip.source.model_base64)).operators.length,3);
assert.throws(()=>T.inspectTFLite(Buffer.from('this is not a tflite model')),/Not a TFLite/);
const corrupt=Buffer.from(bytes);corrupt[4]=0;
assert.throws(()=>T.inspectTFLite(corrupt),/Not a TFLite/);
const fp32=fs.readFileSync(path.replace('int8','fp32'));assert.notEqual(T.inspectTFLite(fp32).input_dtypes[0],'INT8');
console.log('PASS: TFL3, 3 ops, 17,320 bytes parameters, per-channel quantization, board/storage/topology validation, self-contained JSON round-trip, corrupt input rejection, FP32 detection.');
console.log('Generated topology:\n'+p.topology);console.log('Saved JSON bytes:',Buffer.byteLength(JSON.stringify(p)));
