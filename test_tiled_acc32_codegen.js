'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),vm=require('vm');
const C=require('./esp32s3_codegen.js');
const p=require('./model_zoo_examples.js').getProject('squeezenet_int8_project');
const generated=C.generate(p),f=generated.files;
const ini=f['platformio.ini'],cc=f['lib/Noodle/src/noodle_int8_layers.cpp'];
const conf=f['lib/Noodle/src/noodle_config.h'];
assert(ini.includes('[env:esp32-s3-n16r8]'));
assert.equal((ini.match(/\[env:/g)||[]).length,1);
assert(ini.includes('-D NOODLE_INT8_CONV3X3_ACC32=1'));
assert(ini.includes('-D NOODLE_INT8_CONV_IMPL=1'));
assert(ini.includes('-D NOODLE_INT8_POINTWISE_PIXELS=4'));
assert.match(cc,/template <typename Accumulator>\s+static bool q_conv2d_filter_streaming_3x3_impl/);
assert.match(cc,/q_conv3x3_acc32_is_safe/);
assert.match(cc,/q_conv2d_filter_streaming_3x3_impl<int32_t>/);
assert.match(cc,/q_conv2d_filter_streaming_3x3_impl<int64_t>/);
assert.match(conf,/#define NOODLE_INT8_CONV3X3_ACC32 0/);
assert.equal(cc,fs.readFileSync('lib/Noodle/src/noodle_int8_layers.cpp','utf8'));
assert.equal(conf,fs.readFileSync('lib/Noodle/src/noodle_config.h','utf8'));
assert.equal(generated.summary.physicalBuffers,3);
assert.equal(generated.summary.allocatedBytes,1369344);
const scope={console,TextEncoder,TextDecoder,Uint8Array,ArrayBuffer,DataView,atob,btoa};
scope.globalThis=scope;const context=vm.createContext(scope);
for(const n of ['tflite_import.js','noodle_bundle.js','branch_buffer_planner.js','sequential_network_detector.js','s3_serial_sender_bundle.js','esp32s3_chw_transform.js','esp32s3_codegen.js'])
  vm.runInContext(fs.readFileSync(n,'utf8'),context,{filename:n});
context.p=p;
const browser=vm.runInContext('NoodleESP32S3.generate(p)',context).files;
assert.equal(browser['lib/Noodle/src/noodle_config.h'],conf);
assert.equal(browser['lib/Noodle/src/noodle_int8_layers.cpp'],cc);
assert.equal(browser['platformio.ini'],ini);
console.log('PASS: production guarded tiled INT32 and INT64 fallback, Pointwise4, 3-buffer plan, offline browser parity');
